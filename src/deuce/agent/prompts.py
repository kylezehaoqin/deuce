"""Prompts for the analytics agent.

Increment 2 wires this into a LangGraph graph. The graph is mechanical; the
routing prompt is the part that decides whether the product works, so it lives
here on its own and gets its own eval cases.

    Kyle decides what each section says; Claude writes the text. See below.
"""

from __future__ import annotations

from enum import StrEnum


class Route(StrEnum):
    """Where a question goes after the router node.

    Keep this list small. Every route is a branch the eval set has to cover, and
    a router with six options is a router you cannot debug.
    """

    SQL = "sql"
    """Answerable by querying the marts. Numbers, rates, counts, comparisons."""

    SEMANTIC = "semantic"
    """Answerable from match notes / narrative via pgvector. Fuzzy, descriptive."""

    HYBRID = "hybrid"
    """Needs both: a number from SQL plus context that only prose carries."""

    REFUSE = "refuse"
    """Not answerable from this data at all. Saying so is a correct answer."""


# Rendered into SYSTEM_PROMPT at request time. Generated by schema_context.py
# from the dbt manifest (descriptions) plus Postgres (every live column), so the
# agent's view of the schema can never drift from the warehouse.
SCHEMA_CONTEXT_PLACEHOLDER = "{schema_context}"

# Marks a section not written yet. render_system_prompt() refuses to
# render while any section still holds it, so a half-written prompt can never
# reach a model by accident.
UNWRITTEN = "TODO"


# ============================================================================
#  SYSTEM_PROMPT -- written one section at a time.
#
#  WHO DOES WHAT (CLAUDE.md working agreement)
#
#  This prompt is where the project's two layers meet, and the artifact an
#  interviewer reads to judge whether an agent was BUILT or an LLM was called.
#  So every judgment call in it is Kyle's: where the routing line sits, the
#  refusal floor, which tiers may be quoted, the answer shape. Claude presents
#  each one with measured evidence, Kyle decides, Claude writes the text, and
#  the decision goes in lessons/decisions.md. The comments above each section
#  list the decisions that section needs.
#
#  THE SHAPE
#
#  Seven sections, each wrapped in an XML-style tag when rendered. One job per
#  section means each job can be tested and changed on its own -- the same
#  "change one thing at a time" rule as sql/investigations/.
#
#    <role> <data_contract> <routing> <grounding> <refusal> <style> <schema>
#
#  `deuce prompt` prints the rendered prompt with each section's size, and
#  lists the sections still unwritten. <schema> is generated: never edit it.
#
#  SETTLED ALREADY
#
#  - Schema: ALL live columns go in, not descriptions only. Measured: 313
#    columns at ~6,500 tokens, against 129 columns at ~5,200 with descriptions
#    only. The extra ~1,300 tokens buy the 184 columns a model would otherwise
#    have to invent.
#  - The agent shows its SQL. Every answer is auditable; so is every mistake.
#
#  - Routing is INLINE (D7): one structured call returns {route, sql, reason}
#    (graph.AgentStep). The router must see the schema to know what the data
#    can answer -- measured, 4/16 without it, 8/16 with it -- and a separate
#    call with the schema costs ~6,900 more tokens. The route is a field, so
#    it is still scored on its own. <routing> therefore lives in THIS prompt.
#
#  START SMALLER THAN YOU THINK. Settle <role>, <routing> and <grounding> for
#  the SQL route first. Run the 16 cases in tennis-questions.yml. Let the
#  failures tell you what <refusal> and <style> need to say. A prompt written
#  against observed failures beats one written against imagined ones.
# ============================================================================


# ----------------------------------------------------------------------------
#  <role> -- who answers, for whom.
#
#  - The reader is tennis-literate. The prompt should say so, or the model
#    explains what a break point is.
#  - What is the agent FOR? "Answer questions" is not a purpose. "Turn charted
#    match data into a scouting claim with its evidence" is.
#  - One or two sentences. A long role section is a symptom of rules that
#    belong in another section.
# ----------------------------------------------------------------------------
ROLE = UNWRITTEN


# ----------------------------------------------------------------------------
#  <data_contract> -- what the data can and cannot support.
#
#  docs/data-trust.md in compressed form. Its tiers (A verified, B exact, C
#  caveated, D untrustworthy, absent) are the grounding contract. "An answer
#  inherits the lowest tier of its inputs" is the one sentence it must carry.
#
#  Decide how much goes HERE and how much stays in column descriptions (which
#  <schema> already carries). A caveat stated in both places will drift; a
#  caveat in neither is lost. Suggestion: tiers and the inheritance rule here,
#  per-column caveats in the descriptions, and one line telling the model to
#  state the caveat it finds in a column description.
#
#  The caveats the marts already carry, for reference:
#    parsed rates          parse_confidence era; never compare across silently
#    mart_rally_shape      compare players by SLOPE, never by level
#    mart_pressure_index   leverage = a typical server, not this one; tiebreaks NULL
#    mart_player_style     under 20 matches is thin; watch direction_charted_rate
#    mart_matchup          delta includes career change + opponent quality;
#                          77% of pairs have one match
# ----------------------------------------------------------------------------
DATA_CONTRACT = UNWRITTEN


# ----------------------------------------------------------------------------
#  <routing> -- pick a Route.
#
#  The hard cases SOUND semantic but are not:
#
#    "Who's the biggest first-strike player?"      -> SQL (win rate, <=4 shots)
#    "Does Alcaraz look nervous on break points?"  -> REFUSE (not in the data)
#    "Why did Sinner lose that match?"             -> HYBRID, or REFUSE?
#
#  That third one is the interesting one. Decide where the line is and say it
#  explicitly -- vague instructions produce vague routing.
#
#  SEMANTIC and HYBRID have nothing to retrieve from until Increment 3. Decide
#  what the router does with them NOW: route anyway and let the next node
#  refuse, or never pick them yet? Write the decision down either way.
# ----------------------------------------------------------------------------
# Decided by Kyle (D8). Rules 2-3 are the literal-part rule; 5 and 6 come from
# the semantic-01 and "why did X lose" decisions; 4 from direction-03.
ROUTING = """\
Choose one route for each question. Decide from the schema below: it lists
everything the data holds.

- sql: the tables answer the question, or a literal part of it.
- refuse: nothing the question literally asks is in the data, or it asks
  about the future.
- semantic: the answer is only in free text that charters wrote, not in any
  number.
- hybrid: the answer needs a number from the tables AND that free text.

Rules:
1. If the tables answer the whole question, route sql.
2. If they answer a literal part of it, route sql. In `reason`, name the part
   the data cannot answer, and why.
3. If they answer only a related question that was not asked, route refuse.
   In `reason`, name the closest question the data can answer.
4. Shot-by-shot questions need ordered shot records, which do not exist yet:
   the shot after the serve, rally patterns, where the previous ball went.
   Route refuse. Do not use a direction share in their place.
5. Questions about the score are sql: comebacks, breaks, momentum, pressure.
   The score of every point is in the data.
6. "Why" questions are sql. Report what happened: the breaks, the
   highest-leverage points, and who won them. In `reason`, say that the data
   shows what happened, not the cause.
7. Speed, spin, emotion, body language, injuries and future results are not
   in the data. Route refuse.
"""


# ----------------------------------------------------------------------------
#  <grounding> -- every answer cites its evidence.
#
#  The brief's promise is "grounded, cited answers". This is the section that
#  has to make it true. Name the parts of an answer, so the eval can check
#  each one: the claim, the number, n, the filter applied, the SQL, the caveat.
#  A fixed answer shape is what makes grounding scoreable.
# ----------------------------------------------------------------------------
GROUNDING = UNWRITTEN


# ----------------------------------------------------------------------------
#  <refusal> -- say no well.
#
#  Under-supported is worse than unanswered. Put NUMBERS here, not adjectives:
#  tennis-questions.yml says "if N < 20 say the sample is thin".
#
#  The strongest refusal names the CLOSEST answerable question and answers
#  that. guard-01 (serve speed) expects exactly this: speed is not charted,
#  direction is. docs/data-trust.md "Not in the data at all" is the list.
# ----------------------------------------------------------------------------
REFUSAL = UNWRITTEN


# ----------------------------------------------------------------------------
#  <style> -- speak tennis.
#
#  "62% of second serves to the T" is data. "She goes to the body under
#  pressure and it's readable" is an answer. Say how to turn the first into
#  the second WITHOUT dropping the number -- the number is the evidence.
# ----------------------------------------------------------------------------
STYLE = UNWRITTEN


SECTIONS: dict[str, str] = {
    "role": ROLE,
    "data_contract": DATA_CONTRACT,
    "routing": ROUTING,
    "grounding": GROUNDING,
    "refusal": REFUSAL,
    "style": STYLE,
}


def unwritten_sections(sections: dict[str, str] = SECTIONS) -> list[str]:
    """Names of the sections that still hold the UNWRITTEN marker."""
    return [name for name, text in sections.items() if text.strip() == UNWRITTEN]


def assemble(sections: dict[str, str] = SECTIONS) -> str:
    """Wrap each section in its tag. <schema> goes last, as a placeholder."""
    parts = [f"<{name}>\n{text.strip()}\n</{name}>" for name, text in sections.items()]
    parts.append(f"<schema>\n{SCHEMA_CONTEXT_PLACEHOLDER}\n</schema>")
    return "\n\n".join(parts)


def render_system_prompt(
    schema_context: str, sections: dict[str, str] = SECTIONS, allow_unwritten: bool = False
) -> str:
    """The prompt a model receives. Refuses while any section is unwritten.

    `allow_unwritten=True` is for `deuce prompt`, which shows the draft.
    """
    missing = unwritten_sections(sections)
    if missing and not allow_unwritten:
        raise ValueError(f"SYSTEM_PROMPT sections not written yet: {', '.join(missing)}")
    # str.replace, not str.format: the schema and the prose may contain braces.
    return assemble(sections).replace(SCHEMA_CONTEXT_PLACEHOLDER, schema_context)


